-- 7. Create a stored procedure that takes customer_id and returns the name of the category (e.g., 'Action') that the customer rents most often.

drop procedure if exists get_favorite_category;

delimiter ##
create procedure get_favorite_category(in p_customer_id int)
begin
    select c.name as category_name
    from rental r
    join inventory i on r.inventory_id = i.inventory_id
    join film_category fc on i.film_id = fc.film_id
    join category c on fc.category_id = c.category_id
    where r.customer_id = p_customer_id
    group by c.name
    order by count(*) desc
    limit 1;
end ##
delimiter ;

