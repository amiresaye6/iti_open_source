-- 1. Create a function that takes actor_id and returns the concatenated first and last name of this actor. 

drop function if exists get_full_name ;

delimiter ##
create function get_full_name(actor_id int)
returns varchar(255)
reads sql data
begin
	declare full_name varchar(255);
    select concat(first_name, " ", last_name) into full_name
    from actor a
    where a.actor_id = actor_id;
    return full_name;
end ##
delimiter ;

select get_full_name(actor_id)
from actor;

-- 2. Create a function that takes customer_id and returns the total count of rentals made by this customer. 

drop function if exists count_renals;

delimiter ##
create function count_renals(customer_id int)
returns int
reads sql data
begin
	declare output int;
    select count(*) into output
    from rental r
    where r.customer_id = customer_id;
	
	return output;
end ##
delimiter ;

select distinct customer_id, count_renals(customer_id)
from rental;

