-- 10. Create a BEFORE INSERT trigger on the customer table to ensure that any email address entered contains both an @ and a . symbol.

drop trigger if exists trg_validate_email;

delimiter ##
create trigger trg_validate_email
before insert on customer
for each row
begin
    if NEW.email not like '%@%' or NEW.email not like '%.%' then
        signal sqlstate '45000'
        set message_text = 'Error: Invalid email format. Must contain @ and .';
    end if;
end ##
