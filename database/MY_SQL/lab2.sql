-- 4. Create a stored procedure that takes customer_id and returns a result set containing the full name, email, full address, and city of that customer.

drop procedure if exists get_customer_contact;

delimiter ##
create procedure get_customer_contact(in p_customer_id int)
begin
    select 
        concat(first_name, ' ', last_name) as full_name,
        email,
        a.address as full_address,
        c.city
    from customer cu
    join address a on cu.address_id = a.address_id
    join city c on a.city_id = c.city_id
    where cu.customer_id = p_customer_id;
end ##
delimiter ;

call get_customer_contact(5);


-- 5. Create a stored procedure that takes a start_date and end_date and returns the total revenue generated by each store during that period.

drop procedure if exists get_store_revenue;

delimiter ##
create procedure get_store_revenue(in start_date date, in end_date date)
begin
    select 
        s.store_id,
        sum(p.amount) as total_revenue
    from payment p
    join staff st on p.staff_id = st.staff_id
    join store s on st.store_id = s.store_id
    where date(p.payment_date) between start_date and end_date -- yyyy-mm-dd
    group by s.store_id;
end ##
delimiter ;

call get_store_revenue('2005-01-01', '2005-12-31');


-- 6. Create a stored procedure that takes a partial string (e.g., 'dark') and returns all films whose titles contain that string, along with their ratings.

drop procedure if exists search_films;

delimiter ##
create procedure search_films(in genra varchar(255))
begin
    select title, rating
    from film
    where title like concat('%', genra, '%');
end ##
delimiter ;

